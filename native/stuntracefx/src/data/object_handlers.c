{
    uint32_t place = (uint32_t)bank << 16 | word;
    unsigned lo = 0, hi = H_COUNT;

    while (lo < hi) {                   /* PLACES ascends */
        unsigned mid = (lo + hi) / 2;

        if (PLACES[mid] < place)
            lo = mid + 1;
        else
            hi = mid;
    }
    return lo < H_COUNT && PLACES[lo] == place ? (ObjectHandler)lo : H_COUNT;
}

uint16_t object_handler_word(ObjectHandler handler) { return handler < H_COUNT ? (uint16_t)PLACES[handler] : 0; }
uint8_t object_handler_bank(ObjectHandler handler) { return handler < H_COUNT ? (uint8_t)(PLACES[handler] >> 16) : 0; }
